type Language = 'ru' | 'en';

const I18nContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
}>({ language: 'ru', setLanguage: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(
    () => localStorage.getItem('score-language') === 'en' ? 'en' : 'ru',
  );

  useEffect(() => {
    document.documentElement.lang = language;
    localStorage.setItem('score-language', language);
  }, [language]);

  return <I18nContext.Provider value={{ language, setLanguage }}>{children}</I18nContext.Provider>;
}

export function useLanguage() {
  return useContext(I18nContext);
}

export function useT() {
  const { language } = useLanguage();
  return useCallback((key: string) => messages[key]?.[language === 'en' ? 1 : 0] ?? key, [language]);
}
